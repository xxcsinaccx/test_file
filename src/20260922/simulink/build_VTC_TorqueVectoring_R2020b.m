function build_VTC_TorqueVectoring_R2020b()
%BUILD_VTC_TORQUEVECTORING_R2020B Build the VTC-L ASW model and its MIL harness.
%
%   VTC_ASW_R2020b.slx              ASW boundary model. Inputs and outputs are
%                                   Simulink buses that mirror eLSD_Lib
%                                   snapshots. Contains no plant and no CAN stack.
%   VTC_TorqueVectoring_R2020b.slx  MIL harness. Simulates the scenario, the CAN
%                                   reception path, the VTC-R ECU, the vehicle and
%                                   the rear axle. References VTC_ASW_R2020b.
%   VTC_Interface_Buses.mat         Simulink.Bus definitions used by both models.
%
%   Requires MATLAB R2020b with Simulink and Stateflow. Embedded Coder is needed
%   only for code generation of the ASW. Outputs are written next to this file.
%   Calibrations are Constant blocks named by abbreviation (CAL subsystem).

folder = fileparts(mfilename('fullpath'));
addpath(folder);

buses = defineBuses();
save(fullfile(folder, 'VTC_Interface_Buses.mat'), '-struct', 'buses');

aswName = 'VTC_ASW_R2020b';
hrnName = 'VTC_TorqueVectoring_R2020b';
buildASW(aswName, folder);
buildHarness(hrnName, aswName, folder);
fprintf('Built %s and %s in %s\n', aswName, hrnName, folder);
end

