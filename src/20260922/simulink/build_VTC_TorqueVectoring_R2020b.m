function buses = defineBuses()
specs = busSpecs();
busNames = fieldnames(specs);
buses = struct();
for i = 1:numel(busNames)
    rows = specs.(busNames{i});
    el = Simulink.BusElement.empty(0,1);
    for k = 1:size(rows,1)
        e = Simulink.BusElement;
        e.Name = rows{k,1};
        e.DataType = 'single';
        e.Description = rows{k,2};
        el(end+1,1) = e; %#ok<AGROW>
    end
    b = Simulink.Bus;
    b.Elements = el;
    buses.(busNames{i}) = b;
    assignin('base', busNames{i}, b);
end
end

%% ------------------------------------------------------------------------
