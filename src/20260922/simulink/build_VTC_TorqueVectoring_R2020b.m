function addEmptySubsystem(path, pos)
add_block('built-in/SubSystem', path, ...
    'Position', pos, ...
    'ShowName', 'on', ...
    'ContentPreviewEnabled', 'on', ...
    'TreatAsAtomicUnit', 'off');
end

function addMfSubsystem(path, inNames, outNames, code, pos)
addEmptySubsystem(path, pos);
height = max(numel(inNames), numel(outNames)) * 45 + 35;
for k = 1:numel(inNames)
    y = 30 + (k-1)*45;
    add_block('simulink/Ports & Subsystems/In1', [path '/' inNames{k}], ...
        'Position', [20 y 50 y+14], 'Port', num2str(k));
end
addMatlabFunction([path '/Logic'], code, [105 25 245 height]);
for k = 1:numel(outNames)
    y = 45 + (k-1)*45;
    add_block('simulink/Ports & Subsystems/Out1', [path '/' outNames{k}], ...
        'Position', [300 y 330 y+14], 'Port', num2str(k));
end
for k = 1:numel(inNames)
    add_line(path, [inNames{k} '/1'], ['Logic/' num2str(k)], 'autorouting', 'on');
end
for k = 1:numel(outNames)
    add_line(path, ['Logic/' num2str(k)], [outNames{k} '/1'], 'autorouting', 'on');
end
set_param(path, 'Open', 'off');
end

function addMatlabFunction(path, code, pos)
add_block('simulink/User-Defined Functions/MATLAB Function', path, ...
    'Position', pos);
rt = sfroot;
ch = rt.find('-isa', 'Stateflow.EMChart', 'Path', path);
if isempty(ch)
    error('Unable to locate MATLAB Function chart: %s', path);
end
if isstring(code)
    code = join(code, "");
end
ch.Script = char(code);
end

