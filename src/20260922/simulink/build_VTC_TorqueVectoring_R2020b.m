%% ------------------------------------------------------------------------
%  Model utilities
%% ------------------------------------------------------------------------

function closeIfLoaded(mdl)
if bdIsLoaded(mdl)
    close_system(mdl, 0);
end
end

function configureModel(mdl)
set_param(mdl, ...
    'SolverType', 'Fixed-step', ...
    'Solver', 'FixedStepDiscrete', ...
    'FixedStep', '0.005', ...
    'StartTime', '0.0', ...
    'StopTime', '20.0', ...
    'SaveTime', 'on', ...
    'TimeSaveName', 'tout', ...
    'SaveOutput', 'on', ...
    'OutputSaveName', 'yout', ...
    'SignalLogging', 'on', ...
    'SignalLoggingName', 'logsout');
end

function trySetErt(mdl, varargin)
% Applies the ERT target to the ASW model. Harness is not a code generation target.
if nargin > 1 && ~varargin{1}
    return;
end
try
    set_param(mdl, 'SystemTargetFile', 'ert.tlc', 'TargetLang', 'C');
catch ME
    warning('VTC:ERT', 'Could not set ERT target on %s: %s', mdl, ME.message);
end
end

function saveModel(mdl, folder)
f = fullfile(folder, [mdl '.slx']);
try
    save_system(mdl, f, 'ExportToVersion', 'R2020b');
catch
    save_system(mdl, f);
end
end

function addAnnotation(mdl, txt, pos)
note = Simulink.Annotation(mdl, txt);
note.Position = pos;
end

function addRootPort(mdl, kind, name, portNum, pos, busType)
if strcmp(kind, 'Inport')
    blk = 'simulink/Sources/In1';
else
    blk = 'simulink/Sinks/Out1';
end
add_block(blk, [mdl '/' name], 'Position', pos, 'Port', num2str(portNum));
if ~isempty(busType)
    try
        set_param([mdl '/' name], 'OutDataTypeStr', busType);
    catch ME
        warning('VTC:Port', 'Could not set bus type on %s: %s', name, ME.message);
    end
end
end

function addDelay(mdl, name, pos, width) %#ok<INUSL>
add_block('simulink/Discrete/Unit Delay', [mdl '/' name], ...
    'Position', pos, 'SampleTime', '0.005', 'InitialCondition', '0');
end

function wire(sys, src, destinations)
for k = 1:numel(destinations)
    add_line(sys, src, destinations{k}, 'autorouting', 'on');
end
end

