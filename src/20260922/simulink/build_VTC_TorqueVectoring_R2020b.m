function busToVector(sys, names, tag, pos)
% Bus Selector (named elements) followed by Mux into one vector.
% The source must be connected to <tag>_Select/1 by the caller.
names = names(:)';
n = numel(names);
add_block('simulink/Signal Routing/Bus Selector', [sys '/' tag '_Select'], ...
    'OutputSignals', strjoin(names, ','), ...
    'Position', [pos(1) pos(2) pos(1)+60 pos(2)+max(n*12,40)]);
add_block('simulink/Signal Routing/Mux', [sys '/' tag '_Mux'], ...
    'Inputs', num2str(n), ...
    'Position', [pos(1)+120 pos(2) pos(1)+125 pos(2)+max(n*12,40)]);
for k = 1:n
    add_line(sys, [tag '_Select/' num2str(k)], [tag '_Mux/' num2str(k)], 'autorouting', 'on');
end
end

function vectorToBus(sys, names, busName, tag, pos)
% Demux of a vector into named lines, then Bus Creator. The line names become
% the element names, which must match the Simulink.Bus definition.
names = names(:)';
n = numel(names);
add_block('simulink/Signal Routing/Demux', [sys '/' tag '_Demux'], ...
    'Outputs', num2str(n), ...
    'Position', [pos(1) pos(2) pos(1)+5 pos(2)+max(n*12,40)]);
add_block('simulink/Signal Routing/Bus Creator', [sys '/' tag '_Bus'], ...
    'Inputs', num2str(n), ...
    'Position', [pos(1)+120 pos(2) pos(1)+125 pos(2)+max(n*12,40)]);
for k = 1:n
    h = add_line(sys, [tag '_Demux/' num2str(k)], [tag '_Bus/' num2str(k)], 'autorouting', 'on');
    set_param(h, 'Name', names{k});
end
end

